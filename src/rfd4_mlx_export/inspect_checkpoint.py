#!/usr/bin/env python3
"""Inventory the RFD4-Proteina checkpoint: what must be ported, and what can be dropped.

Phase 1 groundwork. Before any weight conversion, this establishes what is actually
in the released bundle — shapes, dtypes, parameter counts per module, and the
encoder/decoder split that decides how much of the autoencoder ships.

Reads the safetensors header only where it can; no model code is imported and no
network is touched.

Usage:
    python inspect_checkpoint.py <snapshot-dir> <out.md>
"""
from __future__ import annotations

import collections
import json
import re
import sys
from pathlib import Path

from safetensors import safe_open

# Modules a *de-novo-only* port could leave out, reported for reference.
#
# THIS PORT SHIPS ALL OF THEM. The AE encoder maps real atom37 geometry into the
# per-residue latent; de-novo generation samples that latent from noise and never
# calls it. But partial diffusion and inverse folding do call it
# (`search/vanilla.py` -> `add_clean_samples`), and upstream's own
# `examples/antibody_design/partial.yaml` is a partial-diffusion run — so dropping
# it would put an upstream example out of reach.
#
# Keeping it costs 0.52 GB fp32 / 0.13 GB int8. Note it is sampled, not
# deterministic (`encoder.py:147` reparameterises), so parity work must pin
# mean-vs-sample explicitly.
OPTIONAL_FOR_DE_NOVO = {
    "autoencoder.encoder": "only used by partial diffusion / inverse folding — SHIPPED anyway",
}


def numel(shape: list[int]) -> int:
    n = 1
    for d in shape:
        n *= d
    return n


def main() -> int:
    snap, out = Path(sys.argv[1]), Path(sys.argv[2])
    cfg = json.loads((snap / "config.json").read_text())

    with safe_open(snap / "model.safetensors", "pt") as f:
        keys = sorted(f.keys())
        entries = []
        for k in keys:
            sl = f.get_slice(k)
            entries.append((k, list(sl.get_shape()), sl.get_dtype()))

    total = sum(numel(s) for _, s, _ in entries)
    dtypes = collections.Counter(d for _, _, d in entries)

    # Parameter counts by module prefix, at two depths.
    def by_depth(depth: int) -> dict[str, int]:
        acc: dict[str, int] = collections.defaultdict(int)
        for k, s, _ in entries:
            acc[".".join(k.split(".")[:depth])] += numel(s)
        return dict(sorted(acc.items(), key=lambda kv: -kv[1]))

    # Repeated blocks, so the port knows how many of each to build.
    blocks: dict[str, list[int]] = {}
    for k, _, _ in entries:
        if m := re.match(r"(.*?)\.(\d+)\.", k):
            blocks.setdefault(m.group(1), [])
            idx = int(m.group(2))
            if idx not in blocks[m.group(1)]:
                blocks[m.group(1)].append(idx)
    blocks = {k: sorted(v) for k, v in blocks.items() if len(v) > 1}

    optional = {
        p: sum(numel(s) for k, s, _ in entries if k.startswith(p + "."))
        for p in OPTIONAL_FOR_DE_NOVO
    }

    L: list[str] = []
    w = L.append
    w("# Checkpoint inventory\n")
    w("Generated by `src/rfd4_mlx_export/inspect_checkpoint.py`. Do not hand-edit.\n")
    w(f"- Snapshot: `{snap.name}`")
    w(f"- `model_type`: `{cfg.get('model_type')}`, format version {cfg.get('format_version')}")
    w(f"- `weights_sha256`: `{cfg.get('weights_sha256')}`")
    w(f"- Tensors: **{len(entries)}**, parameters: **{total:,}**")
    w(f"- Stored dtypes: {dict(dtypes)}\n")

    w("## Parameters by top-level module\n")
    w("| module | params | share |\n|---|---:|---:|")
    for k, v in by_depth(1).items():
        w(f"| `{k}` | {v/1e6:.2f} M | {100*v/total:.1f}% |")

    w("\n## Parameters by submodule\n")
    w("| module | params |\n|---|---:|")
    for k, v in by_depth(2).items():
        if v / total < 0.0005:
            continue
        w(f"| `{k}` | {v/1e6:.2f} M |")

    w("\n## Repeated blocks\n")
    w("| stack | count | indices |\n|---|---:|---|")
    for k, v in sorted(blocks.items()):
        contiguous = v == list(range(len(v)))
        shown = f"0–{v[-1]}" if contiguous else ", ".join(map(str, v))
        w(f"| `{k}` | {len(v)} | {shown} |")

    w("\n## Shipped weight budget\n")
    w("**The whole bundle ships.** Nothing is dropped — partial diffusion, inverse")
    w("folding and upstream's `examples/antibody_design/partial.yaml` all need the AE")
    w("encoder, and 0.13 GB at int8 is not worth putting an upstream example out of reach.\n")
    w("| | params | fp32 | int8 g64 (approx) |\n|---|---:|---:|---:|")
    w(f"| **Shipped (full bundle)** | **{total/1e6:.1f} M** | "
      f"**{total*4/1e9:.2f} GB** | **{total/1e9:.2f} GB** |")
    optional_total = sum(optional.values())
    keep = total - optional_total
    w(f"| _de-novo-only subset, for reference_ | _{keep/1e6:.1f} M_ | "
      f"_{keep*4/1e9:.2f} GB_ | _{keep/1e9:.2f} GB_ |")
    w("")
    for p, why in OPTIONAL_FOR_DE_NOVO.items():
        w(f"- `{p}` ({optional[p]/1e6:.1f} M): {why}.")

    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"{len(entries)} tensors, {total:,} params -> {out}")
    print(f"  shipping all {total/1e6:.1f} M "
          f"({optional_total/1e6:.1f} M of it only for partial diffusion)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
